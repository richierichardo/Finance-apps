function resolveCategoryIconKey(name = '', slug = '') {
    const text = `${slug} ${name}`.toLowerCase();

    if (/(food|grocery|dining|makan|restaurant)/.test(text)) return 'utensils';
    if (/(transport|travel|commute|car)/.test(text)) return 'car';
    if (/(shop|shopping|belanja)/.test(text)) return 'bag';
    if (/(bill|utility|utilities|tax|insurance|service|receipt)/.test(text)) return 'receipt';
    if (/(entertain|netflix|subscription|media|play)/.test(text)) return 'play';
    if (/(health|medical|doctor)/.test(text)) return 'heart';
    if (/(education|school|book|course)/.test(text)) return 'book';
    if (/(salary|income|freelance|bonus|investment|gift|donation)/.test(text)) return 'briefcase';

    return 'tag';
}

export default function CategoryIcon({ name = '', slug = '', className = '' }) {
    const key = resolveCategoryIconKey(name, slug);

    return (
        <span
            className={`inline-flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-indigo-50 text-indigo-600 ${className}`}
        >
            <svg
                className="h-5 w-5"
                xmlns="http://www.w3.org/2000/svg"
                fill="none"
                viewBox="0 0 24 24"
                strokeWidth={1.5}
                stroke="currentColor"
                aria-hidden="true"
            >
                {iconPaths[key]}
            </svg>
        </span>
    );
}

